export type MsgKey = keyof (typeof dict)['en'];

/** Translate a key in the current language; `{name}` placeholders are filled from vars. */
export function t(key: MsgKey, vars?: Record<string, string | number>): string {
	const table = dict[preferences.lang] as Record<string, string>;
	let s = table[key] ?? (dict.en as Record<string, string>)[key] ?? key;
	if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
	return s;
}

export function format_bytes(n: number): string {
	if (!Number.isFinite(n)) return '—';
	const units = ['B', 'KB', 'MB', 'GB', 'TB'];
	let i = 0;
	while (n >= 1000 && i < units.length - 1) {
		n /= 1000;
		i++;
	}
	return `${n >= 100 || i === 0 ? Math.round(n) : n.toFixed(1)} ${units[i]}`;
}

export function format_date(iso: string): string {
	const d = new Date(iso);
	return d.toLocaleString(preferences.lang === 'zh' ? 'zh-CN' : 'en-US', {
		year: 'numeric',
		month: 'short',
		day: 'numeric',
		hour: '2-digit',
		minute: '2-digit',
	});
}

export function format_uptime(sec: number): string {
	const d = Math.floor(sec / 86400);
	const h = Math.floor((sec % 86400) / 3600);
	const m = Math.floor((sec % 3600) / 60);
	if (d > 0) return t('common.day', { d, h });
	if (h > 0) return t('common.hour', { h, m });
	return t('common.min', { n: m });
}
